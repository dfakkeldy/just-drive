#!/usr/bin/env python3
"""The Just Drive front page map: a small land outline, as one SVG path.

Inputs (not in git): data/raw/far-views/regional-240m.tif (MRDEM, 240 m; land is every cell above 0.5 m) and each\narea's village point from data/baked (terrain/ and areas/*/manifest.json). Rerun it when an area is added.
Output (in git, so CI and the site build need no data/): pipeline/just-map.json.
Usage: python3 pipeline/40_bake_just_map.py [--data-root data]
"""
import argparse
import json
from pathlib import Path
import numpy as np
from osgeo import gdal
from shapely.geometry import Polygon, box
from shapely.ops import unary_union

# The frame, in NAD83(CSRS) / UTM 20N metres: western Cape Breton from north of Mabou down across the Strait of Canso.
FRAME = (586000, 5034000, 668000, 5118000)
SCALE = 100  # metres per SVG unit: the frame is 820 x 840 units
LAND_TOLERANCE = 260  # simplification in metres
MIN_ISLAND = 2_500_000  # m²; smaller islands are left out


def svg_point(x, y):
    return f'{(x - FRAME[0]) / SCALE:.1f} {(FRAME[3] - y) / SCALE:.1f}'


def ring_path(coords):
    points = [svg_point(x, y) for x, y in coords]
    return 'M' + 'L'.join(points[:-1]) + 'Z'


def land(dem_path):
    gdal.UseExceptions()
    data = gdal.Open(str(dem_path))
    ox, px, _, oy, _, py = data.GetGeoTransform()
    band = data.GetRasterBand(1)
    heights = band.ReadAsArray().astype(np.float32)
    nodata = band.GetNoDataValue()
    above = (heights > 0.5) & (heights != nodata)
    # One square per land cell, merged: honest at 240 m and then smoothed by the simplification.
    rows, cols = np.nonzero(above)
    x0, y0, x1, y1 = FRAME
    keep = (ox + cols * px < x1 + 2000) & (ox + (cols + 1) * px > x0 - 2000) & (oy + rows * py > y0 - 2000) & (oy + (rows + 1) * py < y1 + 2000)
    rows, cols = rows[keep], cols[keep]
    # Merge runs of land cells in each row first, so the union stays fast.
    pieces = []
    for row in np.unique(rows):
        line = np.sort(cols[rows == row])
        start = prev = line[0]
        for col in list(line[1:]) + [None]:
            if col is not None and col == prev + 1:
                prev = col; continue
            pieces.append(box(ox + start * px, oy + (row + 1) * py, ox + (prev + 1) * px, oy + row * py))
            if col is not None: start = prev = col
    merged = unary_union(pieces).intersection(box(*FRAME)).simplify(LAND_TOLERANCE, preserve_topology=True)
    polygons = [merged] if isinstance(merged, Polygon) else list(merged.geoms)
    paths = []
    for polygon in polygons:
        if polygon.area < MIN_ISLAND: continue
        paths.append(ring_path(polygon.exterior.coords))
        for hole in polygon.interiors:
            if Polygon(hole).area >= MIN_ISLAND: paths.append(ring_path(hole.coords))
    return ''.join(paths)


def villages(root):
    """Each area's village point (its manifest), where the front page puts its pin."""
    found = {'mabou': json.loads((root / 'baked/terrain/manifest.json').read_text())['village']}
    for manifest in sorted(root.glob('baked/areas/*/manifest.json')):
        found[manifest.parent.name] = json.loads(manifest.read_text())['village']
    return {area: [round((x - FRAME[0]) / SCALE, 1), round((FRAME[3] - y) / SCALE, 1)] for area, (x, y) in found.items()}


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--data-root', default='data')
    root = Path(parser.parse_args().data_root)
    out = {
        'note': 'Generated by pipeline/40_bake_just_map.py. SVG units are 100 m; x east, y south from the frame corner.',
        'crs': 'EPSG:2961', 'frame': FRAME, 'scale': SCALE,
        'land': land(root / 'raw/far-views/regional-240m.tif'),
        'pins': villages(root),
    }
    target = Path(__file__).with_name('just-map.json')
    target.write_text(json.dumps(out, separators=(',', ':')) + '\n')
    print(f'{target}: {target.stat().st_size} bytes')


if __name__ == '__main__':
    main()
