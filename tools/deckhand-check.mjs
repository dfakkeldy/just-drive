import assert from 'node:assert/strict';
import { Deckhand, DECKHAND } from '../web/src/deckhand.ts';
import { Vector3 } from '../web/node_modules/three/build/three.module.js';
const village=[624271,5103301];
let ground=2,level=8;
const terrain={surfaceAt:()=>({level}),meshHeightAt:()=>ground,seaLevel:-.2};
const d=new Deckhand(village,terrain);
const x=DECKHAND.e-village[0],z=village[1]-DECKHAND.n,cam=new Vector3(x,10,z);
d.update(1/60,{x:x+40,z},cam);assert.ok(d.pointing,'40 m is included');
assert.ok(Math.abs(d.body.rotation.y-Math.PI/2)<1e-6,'faces car');
d.update(1/60,{x:x+40.01,z},cam);assert.equal(d.pointing,false,'outside 40 m rests');
d.update(1/60,{x:x-10,z},cam);assert.ok(d.pointing);assert.ok(d.arm.visible);
d.group.updateMatrixWorld(true);
const hand=d.arm.localToWorld(new Vector3(0,0,.69)).sub(d.arm.getWorldPosition(new Vector3()));
assert.ok(hand.x>0&&hand.z<0,'arm points north-east to stop, independently of torso');
d.update(.1,{x:x-10,z:z-10},cam);
assert.equal(d.body.scale.x,-1,'north-west car uses the left pointing shoulder');
const yaw=d.body.rotation.y;d.update(0,{x:x+10,z},cam);assert.equal(d.body.rotation.y,yaw,'pause keeps pose');
d.update(.1,{x,z},new Vector3(x+349.9,10,z));assert.equal(d.group.visible,true,'camera inside 350 m shows figure');
d.update(.1,{x,z},new Vector3(x+350.1,10,z));assert.equal(d.group.visible,false,'camera beyond 350 m hides figure');
ground=-1;d.update(.1,{x,z},cam);assert.equal(d.group.visible,false,'water hides figure');
ground=2;level=5;d.update(.1,{x,z},cam);assert.equal(d.group.visible,false,'coarse land hides figure');
console.log('PASS deckhand range, aim, pause, 350 m camera and ground gates');
