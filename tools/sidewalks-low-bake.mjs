// Transport-only bake. Reads existing desktop packs; writes generated web JSON in an explicit work root.
import assert from 'node:assert/strict';
import {readFileSync,writeFileSync,mkdirSync,realpathSync,existsSync} from 'node:fs';
import {resolve,dirname,basename} from 'node:path';
import {fileURLToPath} from 'node:url';
import {gzipSync,gunzipSync} from 'node:zlib';
import {createHash} from 'node:crypto';
import {execFileSync} from 'node:child_process';
export const areas=['mabou','porthood','pointtupper'];
export const areaBase=area=>area==='mabou'?'terrain':`areas/${area}`;
export const sha=bytes=>createHash('sha256').update(bytes).digest('hex');
export const canonical=value=>JSON.stringify(value,(_key,v)=>v&&typeof v==='object'&&!Array.isArray(v)?Object.fromEntries(Object.keys(v).sort().map(k=>[k,v[k]])):v);
export function selectLow(data){
 return {id:data.id,roads:data.roads,plan:data.plans[1],tiles:data.tiles,compiled:data.compiled[1],terrain:Object.fromEntries(Object.entries(data.terrain).map(([key,t])=>[key,{pixels:t.pixels,members:t.members[1],...(t.heightMembers?{heightMembers:t.heightMembers[1]}:{})}]))};
}
export const unpack=bytes=>JSON.parse(gunzipSync(Buffer.from(JSON.parse(bytes).payload,'base64')));
export function graphHashes(data){
 const hash=value=>sha(canonical(value));
 return {graph:hash(data),geometry:hash(data.compiled.geometries),jobs:hash({points:data.compiled.points,topOwners:data.compiled.topOwners,topCount:data.compiled.topCount,bridgeRefs:data.compiled.bridgeRefs,bridgeJobs:data.compiled.bridgeJobs,jobs:data.compiled.jobs}),masks:hash({tiles:data.tiles,pixels:Object.fromEntries(Object.entries(data.terrain).map(([k,t])=>[k,t.pixels]))}),dependencies:hash({coverage:data.compiled.coverage,jobs:data.compiled.jobs.map(j=>({drawTiles:j.drawTiles,heightTiles:j.heightTiles})),members:Object.fromEntries(Object.entries(data.terrain).map(([k,t])=>[k,{members:t.members,heightMembers:t.heightMembers}]))})};
}
export function assertWorkRoot(workRoot){
 const root=resolve(import.meta.dirname,'..');
 const primaryRoot=dirname(resolve(execFileSync('git',['rev-parse','--path-format=absolute','--git-common-dir'],{cwd:root,encoding:'utf8'}).trim()));
 const real=p=>{const tail=[];while(!existsSync(p)){tail.unshift(basename(p));p=dirname(p);}return resolve(realpathSync(p),...tail);};
 const target=real(resolve(workRoot)),baked=real(resolve(root,'data/baked')),inside=(p,base)=>p===base||p.startsWith(base+'/');
 assert.notEqual(target,real(root),'write bake needs an isolated work root');
 for(const output of [target,real(resolve(workRoot,'data/baked')),real(resolve(workRoot,'web/src'))])
  for(const protectedPath of [baked,resolve(dirname(baked),'site'),resolve(root,'data/site'),resolve(root,'web'),...['web','data/baked','data/site'].map(p=>resolve(primaryRoot,p))])assert.ok(!inside(output,real(protectedPath)),'work root must not write primary or selected baked/site/source destinations');
}
export function bakeLow(sourceRoot,workRoot){
 assertWorkRoot(workRoot);const files=[],assets={};
 for(const area of areas){
  const source=`web/src/sidewalks-packed-${area}.json`,bytes=readFileSync(resolve(sourceRoot,source)),selected=selectLow(unpack(bytes));
  const output=Buffer.from(JSON.stringify({version:3,quality:'low',payload:gzipSync(Buffer.from(JSON.stringify(selected)),{level:9}).toString('base64')})+'\n');
  assets[area]={};
  for(const [quality,body]of [['desktop',bytes],['low',output]]){
   const file=`sidewalks-${quality}.json`,path=`data/baked/${areaBase(area)}/${file}`,dest=resolve(workRoot,path);mkdirSync(dirname(dest),{recursive:true});writeFileSync(dest,body);
   const descriptor={file,bytes:body.length,sha256:sha(body)};assets[area][quality]=descriptor;files.push({path,...descriptor,area,quality});
  }
 }
 const source='// Generated by tools/sidewalks-low-bake.mjs. Payload updates require a reviewed source change.\nexport interface SidewalkAsset {readonly file:string;readonly bytes:number;readonly sha256:string}\nexport const SIDEWALK_ASSETS:Readonly<Record<string,{readonly desktop:SidewalkAsset;readonly low:SidewalkAsset}|undefined>> = '+JSON.stringify(assets,null,2)+';\n';
 mkdirSync(resolve(workRoot,'web/src'),{recursive:true});writeFileSync(resolve(workRoot,'web/src/sidewalks-assets.ts'),source);
 return files;
}
if(process.argv[1]===fileURLToPath(import.meta.url)){
 const guardAt=process.argv.indexOf('--assert-work-root');
 if(guardAt>=0){assert.ok(process.argv[guardAt+1],'guard needs a work root');assertWorkRoot(process.argv[guardAt+1]);console.log('PASS isolated work root; no output written');process.exit(0);}
 const at=process.argv.indexOf('--work-root');assert.ok(at>=0&&process.argv[at+1],'explicit --work-root is required; no baked/site writes');
 const source=process.argv.indexOf('--source-root'),sourceRoot=source>=0?resolve(process.argv[source+1]):resolve(import.meta.dirname,'..'),workRoot=resolve(process.argv[at+1]);
 const files=bakeLow(sourceRoot,workRoot);writeFileSync(resolve(workRoot,'low-payload-manifest.json'),JSON.stringify({sourceRoot,files},null,2)+'\n');console.log(JSON.stringify({workRoot,files},null,2));
}
